def translate(key, lang=DEFAULT_LANGUAGE):
    """Return the key translated into `lang` with English fallback.

    Lookup order: the language's own dictionary, then a related language
    (``LANG_FALLBACK``), then the English key itself.
    """
    if not lang or lang == DEFAULT_LANGUAGE:
        return key
    legacy_nav_keys = {
        'Home': 'home', 'About': 'aboutNav', 'How It Works': 'howNav',
        'Find Work': 'findWork', 'Hire Workers': 'hireWorkers',
        'Language': 'language', 'Login': 'loginNav', 'Register': 'registerNav',
    }
    lookup_key = legacy_nav_keys.get(key, key)
    value = TRANSLATIONS.get(lang, {}).get(lookup_key)
    if value is not None:
        return value
    fallback = LANG_FALLBACK.get(lang)
    if fallback:
        value = TRANSLATIONS.get(fallback, {}).get(lookup_key)
        if value is not None:
            return value
    return key


# --- Thread-local current language -------------------------------------------
# Middleware sets this per request so filters/templates can translate dynamic
# values (e.g. job titles) without threading the language through every call.

_state = threading.local()


def set_current_language(lang):
    _state.lang = lang


def get_current_language():
    return getattr(_state, 'lang', DEFAULT_LANGUAGE)


def translate_current(key):
    return translate(key, get_current_language())
